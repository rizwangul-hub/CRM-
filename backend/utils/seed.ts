function daysAgo(days: number, hoursOffset = 14): Date {
  const d = new Date();
  d.setDate(d.getDate() - days);
  d.setHours(hoursOffset, 20, 0, 0);
  return d;
}

function daysFromNow(days: number): Date {
  const d = new Date();
  d.setDate(d.getDate() + days);
  d.setHours(23, 59, 0, 0);
  return d;
}

function monthsAgo(months: number, dayOfMonth = 12): Date {
  const now = new Date();
  return new Date(now.getFullYear(), now.getMonth() - months, dayOfMonth, 15, 0, 0, 0);
}

